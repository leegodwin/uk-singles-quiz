create table if not exists public.quiz_scores (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 24),
  score smallint not null check (score >= 0),
  total smallint not null check (total > 0),
  mode text not null check (mode in ('easy', 'medium', 'hard')),
  created_at timestamptz not null default now(),
  constraint quiz_scores_score_within_total check (score <= total)
);

alter table public.quiz_scores enable row level security;

grant select, insert on public.quiz_scores to anon, authenticated;
grant usage, select on sequence public.quiz_scores_id_seq to anon, authenticated;

drop policy if exists "Anyone can read quiz scores" on public.quiz_scores;
create policy "Anyone can read quiz scores"
  on public.quiz_scores for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can submit valid quiz scores" on public.quiz_scores;
create policy "Anyone can submit valid quiz scores"
  on public.quiz_scores for insert
  to anon, authenticated
  with check (
    char_length(btrim(name)) between 1 and 24
    and score >= 0
    and total > 0
    and score <= total
    and mode in ('easy', 'medium', 'hard')
  );
